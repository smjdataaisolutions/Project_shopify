CREATE TABLE shops (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shop_domain TEXT NOT NULL,
  shopify_shop_gid TEXT,
  installed_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  uninstalled_at TIMESTAMPTZ,
  status TEXT NOT NULL DEFAULT 'active',
  sync_status TEXT NOT NULL DEFAULT 'pending',
  last_synced_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT uq_shops_shop_domain UNIQUE (shop_domain),
  CONSTRAINT ck_shops_canonical_domain CHECK (
    shop_domain = lower(shop_domain)
    AND shop_domain ~ '^[a-z0-9]([a-z0-9-]*[a-z0-9])?\.myshopify\.com$'
  ),
  CONSTRAINT ck_shops_status CHECK (
    status IN ('active', 'inactive', 'uninstalled')
  ),
  CONSTRAINT ck_shops_sync_status CHECK (
    sync_status IN ('pending', 'running', 'completed', 'failed')
  )
);

