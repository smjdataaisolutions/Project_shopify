DECLARE
  table_name TEXT;
  missing_count BIGINT;
BEGIN
  FOREACH table_name IN ARRAY ARRAY[
    'products', 'product_variants', 'locations', 'inventory',
    'orders', 'order_line_items', 'shopify_sync_state'
  ] LOOP
    EXECUTE format('SELECT count(*) FROM %I WHERE shop_id IS NULL', table_name)
      INTO missing_count;
    IF missing_count <> 0 THEN
      RAISE EXCEPTION '% contains % records without a tenant', table_name, missing_count;
    END IF;
  END LOOP;
END $$;

