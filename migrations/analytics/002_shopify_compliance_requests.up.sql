-- Public distribution readiness: durable, PII-minimized data-request queue.

CREATE TABLE shopify_compliance_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shop_id BIGINT NOT NULL,
  shopify_request_id TEXT NOT NULL,
  topic TEXT NOT NULL,
  order_ids JSONB NOT NULL DEFAULT '[]'::jsonb,
  status TEXT NOT NULL DEFAULT 'pending',
  received_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  due_at TIMESTAMPTZ NOT NULL DEFAULT (clock_timestamp() + INTERVAL '30 days'),
  completed_at TIMESTAMPTZ,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT uq_compliance_request_shop UNIQUE (shop_id, shopify_request_id),
  CONSTRAINT fk_compliance_request_shop FOREIGN KEY (shop_id)
    REFERENCES shops (id) ON DELETE RESTRICT,
  CONSTRAINT ck_compliance_request_topic CHECK (
    topic = 'customers/data_request'
  ),
  CONSTRAINT ck_compliance_request_status CHECK (
    status IN ('pending', 'exported', 'completed', 'failed')
  ),
  CONSTRAINT ck_compliance_request_order_ids CHECK (
    jsonb_typeof(order_ids) = 'array'
  )
);

CREATE INDEX ix_compliance_requests_shop_status_due
  ON shopify_compliance_requests (shop_id, status, due_at);
